/**
 * 卡牌仓储类，提供纯粹的随机抽取逻辑
 * 核心原则：卡牌随机抽取与用户回答严格分开，不根据用户文本调整抽卡结果
 */
export class CardRepository {
  static getAllImageCards(): ImageCard[] {
    return [...IMAGE_CARDS];
  }

  static getImageCardById(id: string): ImageCard | undefined {
    return IMAGE_CARDS.find((c) => c.id === id);
  }

  /**
   * 随机挑选 N 张不重复的图卡候选，供用户点选
   */
  static getRandomImageCandidates(count: number = 5): ImageCard[] {
    const shuffled = [...IMAGE_CARDS].sort(() => 0.5 - Math.random());
    return shuffled.slice(0, Math.min(count, IMAGE_CARDS.length));
  }

  static getAllWordCards(): WordCard[] {
    return [...WORD_CARDS];
  }

  static getWordCardById(id: string): WordCard | undefined {
    return WORD_CARDS.find((c) => c.id === id);
  }

  /**
   * 随机挑选 1 张或 N 张词语卡
   */
  static getRandomWordCandidates(count: number = 3): WordCard[] {
    const shuffled = [...WORD_CARDS].sort(() => 0.5 - Math.random());
    return shuffled.slice(0, Math.min(count, WORD_CARDS.length));
  }
}
